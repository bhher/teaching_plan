CREATE DATABASE school_db 
CHARACTER SET utf8mb4 
COLLATE utf8mb4_unicode_ci;

USE school_db;

-- 테이블 생성
CREATE TABLE student (
    student_id INT PRIMARY KEY AUTO_INCREMENT,
    name VARCHAR(50) NOT NULL,
    department VARCHAR(50),
    grade INT,
    korean INT,
    english INT,
    math INT,
    science INT,
    total_score INT,
    average DECIMAL(5,2)
) CHARACTER SET utf8mb4 
  COLLATE utf8mb4_unicode_ci;

